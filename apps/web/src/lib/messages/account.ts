export function localizeNotification(item: NotificationItem, locale: Locale): Pick<NotificationItem, "title" | "text"> {
  for (const template of notificationTemplates) {
    if (item.type !== template.type || item.title !== template.title.ru) continue;
    const match = template.pattern.exec(item.text);
    if (!match) continue;
    const values: Record<string, string> = {};
    template.fields.forEach((field, index) => {
      const value = match[index + 1];
      values[field] = field === "status" ? statusLabel(value, locale) : value;
    });
    return {
      title: template.title[locale],
      text: template.text[locale].replace(/\{(\w+)\}/g, (token, key: string) => values[key] ?? token),
    };
  }
  return { title: item.title, text: item.text };
}
